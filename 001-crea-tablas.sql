create table tk_usuarios (
    id_usuario integer GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    apellido VARCHAR2(100) NOT NULL,
    username VARCHAR2(100) NOT NULL UNIQUE,
    email  VARCHAR2(100) ,
    telefono VARCHAR2(15) ,
    ubicacion VARCHAR2(100) ,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    usuario_creacion VARCHAR2(128) DEFAULT USER NOT NULL,
    fecha_actualizacion TIMESTAMP,
    usuario_actualizacion VARCHAR2(128) ,
    activo CHAR(1) DEFAULT 'S'
); 

ALTER TABLE tk_usuarios ADD CONSTRAINT tk_usuarios_activo_ck CHECK (activo IN ('S', 'N'));

create table tk_roles (
   id_rol INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
   nombre_rol VARCHAR2(100) NOT NULL unique,
   fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
   usuario_creacion VARCHAR2(100) default user NOT NULL,
    fecha_actualizacion TIMESTAMP,
    usuario_actualizacion VARCHAR2(100)
);


CREATE TABLE tk_usuarios_roles (
    id_usuario_rol INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    id_rol INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion VARCHAR2(128) DEFAULT user NOT NULL,
    fecha_actualizacion TIMESTAMP,
    usuario_actualizacion VARCHAR2(128),
    CONSTRAINT tk_usuarios_roles_id_rol_fk FOREIGN KEY (id_rol) REFERENCES tk_roles(id_rol),
    CONSTRAINT tk_usuarios_roles_id_usuario_fk FOREIGN KEY (id_usuario) REFERENCES tk_usuarios(id_usuario)
);

create table tk_comentarios(
    id_comentario integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
    id_ticket integer NOT NULL, 
    id_usuario integer NOT NULL,
    comentario varchar2(500) NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
    usuario_creacion VARCHAR2(128) default user NOT NULL,
    fecha_actualizacion TIMESTAMP,
    usuario_actualizacion VARCHAR2(128)--,
);

CREATE TABLE TK_AREAS (
    ID_AREA integer GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
    NOMBRE_AREA VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(300),
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USUARIO_CREACION VARCHAR2(128) DEFAULT USER NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP,
    USUARIO_ACTUALIZACION VARCHAR2(128),
    ACTIVA CHAR(1) DEFAULT 'S'
);

Create table Tk_CATEGORIAS (
    ID_CATEGORIAS integer generated by default on null as identity (start with 1 increment by 1) primary key,
    NOMBRE_CATEGORIAS varchar2 (100) not null,
    DESCRIPCION varchar2 (300) not null,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
    USUARIO_CREACION VARCHAR2(128) default user NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP ,
    USUARIO_ACTUALIZACION VARCHAR2(128)
);

CREATE TABLE TK_TICKET_ADJUNTOS (
    ID_ADJUNTO INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
    ID_TICKET integer NOT NULL,
    NOMBRE_ARCHIVO VARCHAR2(255),
    EXTENSION VARCHAR2(20),
    MIME_TYPE VARCHAR2(100), 
    TAMANO_BYTES integer,
    ARCHIVO BLOB,  
    FECHA_CARGA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ID_USUARIO integer NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
    USUARIO_CREACION VARCHAR2(128) DEFAULT USER NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP,
    USUARIO_ACTUALIZACION VARCHAR2(128),
    ACTIVA CHAR(1) DEFAULT 'S'
);

create TABLE TK_CAT_PRIORIDADES(
    ID_PRIORIDAD integer GENERATED BY DEFAULT on null as identity (start with 1 increment by 1),
    NOMBRE_PRIORIDAD VARCHAR2(50) NOT NULL,
    NIVEL INTEGER NOT NULL,
    TIEMPO_SLA_HORAS NUMBER NOT NULL, 
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
    USUARIO_CREACION VARCHAR2(128) DEFAULT USER NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP,
    USUARIO_ACTUALIZACION VARCHAR2(128),
    CONSTRAINT TK_CAT_PRIORIDADES_ID_PRIORIDAD_PK
    PRIMARY KEY (ID_PRIORIDAD),
    CONSTRAINT TK_CAT_PRIORIDADES_NOMBRE_UK
    UNIQUE (NOMBRE_PRIORIDAD)
);

CREATE TABLE TK_CAT_ESTADOS (
    ID_ESTADO INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY NOT NULL,
    NOMBRE_ESTADO VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION_ESTADO VARCHAR2(200),
    CERRADO CHAR(1) DEFAULT 'N' NOT NULL, -- (S/N) Indica si el estado es de cierre de ticket
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP not null,
    USUARIO_CREACION VARCHAR2(128) DEFAULT USER NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP,
    USUARIO_ACTUALIZACION VARCHAR2(128)
);


