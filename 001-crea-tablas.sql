CREATE TABLE TK_TICKETS
(
    ID_TICKET             INTEGER
                          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_TICKET         VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPCION           CLOB NOT NULL,
    ID_USUARIO_REPORTA    INTEGER NOT NULL,
    ID_TECNICO_ASIGNADO   INTEGER,
    ID_CATEGORIA          INTEGER NOT NULL,
    ID_PRIORIDAD          INTEGER NOT NULL,
    ID_ESTADO             INTEGER NOT NULL,
    ID_AREA               INTEGER NOT NULL,
    FECHA_SOLICITUD       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ASIGNACION      TIMESTAMP(6),
    FECHA_INICIO          TIMESTAMP(6),
    FECHA_RESOLUCION      TIMESTAMP(6),
    FECHA_CIERRE          TIMESTAMP(6),
    HORAS_ESTIMADAS       NUMBER(10,2),
    HORAS_REALES          NUMBER(10,2),
    PORCENTAJE_AVANCE     NUMBER(5,2) DEFAULT 0 NOT NULL,
    DESCRIPCION_SOLUCION  CLOB,
    USUARIO_CREACION      VARCHAR2(128 CHAR) DEFAULT USER NOT NULL,
    FECHA_CREACION        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    USUARIO_ACTUALIZACION VARCHAR2(128 CHAR),
    FECHA_ACTUALIZACION   TIMESTAMP(6),

    CONSTRAINT TK_TICKETS_PK
        PRIMARY KEY (ID_TICKET),

    CONSTRAINT TK_TICKETS_REPORTA_FK
        FOREIGN KEY (ID_USUARIO_REPORTA)
        REFERENCES TK_USUARIOS (ID_USUARIO),

    CONSTRAINT TK_TICKETS_TECNICO_FK
        FOREIGN KEY (ID_TECNICO_ASIGNADO)
        REFERENCES TK_USUARIOS (ID_USUARIO),

    CONSTRAINT TK_TICKETS_CATEGORIA_FK
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES TK_CATEGORIAS (ID_CATEGORIA),

    CONSTRAINT TK_TICKETS_PRIORIDAD_FK
        FOREIGN KEY (ID_PRIORIDAD)
        REFERENCES TK_CAT_PRIORIDADES (ID_PRIORIDAD),

    CONSTRAINT TK_TICKETS_ESTADO_FK
        FOREIGN KEY (ID_ESTADO)
        REFERENCES TK_CAT_ESTADOS (ID_ESTADO),

    CONSTRAINT TK_TICKETS_AREA_FK
        FOREIGN KEY (ID_AREA)
        REFERENCES TK_AREAS (ID_AREA),

    CONSTRAINT TK_TICKETS_AVANCE_CK
        CHECK (PORCENTAJE_AVANCE BETWEEN 0 AND 100),

    CONSTRAINT TK_TICKETS_HORAS_EST_CK
        CHECK (HORAS_ESTIMADAS IS NULL OR HORAS_ESTIMADAS >= 0),

    CONSTRAINT TK_TICKETS_HORAS_REAL_CK
        CHECK (HORAS_REALES IS NULL OR HORAS_REALES >= 0),

    CONSTRAINT TK_TICKETS_FECHAS_CK
        CHECK (
            (FECHA_ASIGNACION IS NULL OR FECHA_ASIGNACION >= FECHA_SOLICITUD)
            AND
            (FECHA_INICIO IS NULL OR FECHA_ASIGNACION IS NULL OR FECHA_INICIO >= FECHA_ASIGNACION)
            AND
            (FECHA_RESOLUCION IS NULL OR FECHA_INICIO IS NULL OR FECHA_RESOLUCION >= FECHA_INICIO)
            AND
            (FECHA_CIERRE IS NULL OR FECHA_RESOLUCION IS NULL OR FECHA_CIERRE >= FECHA_RESOLUCION)
        )
);

COMMENT ON TABLE TK_TICKETS IS
    'Tickets o solicitudes de soporte registradas en el sistema';

COMMENT ON COLUMN TK_TICKETS.ID_USUARIO_REPORTA IS
    'Usuario que reportó la solicitud o incidencia';

COMMENT ON COLUMN TK_TICKETS.ID_TECNICO_ASIGNADO IS
    'Técnico responsable de atender el ticket';

COMMENT ON COLUMN TK_TICKETS.PORCENTAJE_AVANCE IS
    'Porcentaje de avance del ticket entre 0 y 100';


