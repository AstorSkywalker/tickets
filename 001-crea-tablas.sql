CREATE TABLE TK_USUARIOS
(
    ID_USUARIO            INTEGER
                          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE                VARCHAR2(100 CHAR) NOT NULL,
    APELLIDO              VARCHAR2(100 CHAR) NOT NULL,
    USERNAME              VARCHAR2(100 CHAR) NOT NULL,
    EMAIL                 VARCHAR2(254 CHAR),
    TELEFONO              VARCHAR2(30 CHAR),
    UBICACION             VARCHAR2(150 CHAR),
    FECHA_CREACION        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    USUARIO_CREACION      VARCHAR2(128 CHAR) DEFAULT USER NOT NULL,
    FECHA_ACTUALIZACION   TIMESTAMP(6),
    USUARIO_ACTUALIZACION VARCHAR2(128 CHAR),
    ACTIVO                CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT TK_USUARIOS_PK
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT TK_USUARIOS_USERNAME_UK
        UNIQUE (USERNAME),

    CONSTRAINT TK_USUARIOS_EMAIL_UK
        UNIQUE (EMAIL),

    CONSTRAINT TK_USUARIOS_ACTIVO_CK
        CHECK (ACTIVO IN ('S', 'N'))
);

COMMENT ON TABLE TK_USUARIOS IS
    'Usuarios que reportan, atienden o administran tickets del sistema de help desk';

COMMENT ON COLUMN TK_USUARIOS.ID_USUARIO IS
    'Identificador único del usuario';

COMMENT ON COLUMN TK_USUARIOS.USERNAME IS
    'Nombre de usuario utilizado para identificar al usuario en el sistema';

COMMENT ON COLUMN TK_USUARIOS.ACTIVO IS
    'Indica si el usuario está activo: S=Sí, N=No';


