    ID_TECNICO_ASIGNADO_NUEVO INTEGER,
    ID_CATEGORIA_VIEJO INTEGER,
    ID_CATEGORIA_NUEVO INTEGER,
    ID_PRIORIDAD_VIEJO INTEGER,
    ID_PRIORIDAD_NUEVO INTEGER,
    ID_AREA_VIEJO INTEGER,
    ID_AREA_NUEVO INTEGER,
    HORAS_ESTIMADAS_VIEJO NUMBER(5,2),
    HORAS_ESTIMADAS_NUEVO NUMBER(5,2),
    HORAS_REALES_VIEJO NUMBER(5,2),
    HORAS_REALES_NUEVO NUMBER(5,2),
    PORCENTAJE_AVANCE_VIEJO NUMBER(5,2),
    PORCENTAJE_AVANCE_NUEVO NUMBER(5,2),
    NOMBRE_TICKET_VIEJO VARCHAR2(50),
    NOMBRE_TICKET_NUEVO VARCHAR2(50),
    DESCRIPCION_VIEJO CLOB,
    DESCRIPCION_NUEVO CLOB,
    DESCRIPCION_SOLUCION_VIEJO CLOB,
    DESCRIPCION_SOLUCION_NUEVO CLOB,
    USUARIO_CREACION_VIEJO VARCHAR2(128),
    USUARIO_CREACION_NUEVO VARCHAR2(128),
    FECHA_CREACION_VIEJO TIMESTAMP(6),
    FECHA_CREACION_NUEVO TIMESTAMP(6),
    USUARIO_ACTUALIZACION_VIEJO VARCHAR2(128),
    USUARIO_ACTUALIZACION_NUEVO VARCHAR2(128),
    FECHA_ACTUALIZACION_VIEJO TIMESTAMP(6),
    FECHA_ACTUALIZACION_NUEVO TIMESTAMP(6),
    USUARIO_CAMBIO VARCHAR2(128) DEFAULT USER NOT NULL,
    FECHA_CAMBIO TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT tk_tickets_historial_operacion_ck CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
    CONSTRAINT tk_tickets_historial_ticket_fk FOREIGN KEY (id_ticket) REFERENCES tk_tickets(id_ticket),
    CONSTRAINT tk_tickets_historial_estado_ant_fk FOREIGN KEY (id_estado_anterior) REFERENCES tk_estados(id_estado),
    CONSTRAINT tk_tickets_historial_estado_new_fk FOREIGN KEY (id_estado_nuevo) REFERENCES tk_estados(id_estado)
);

COMMENT ON TABLE TK_TICKETS_HISTORIAL IS 'Histórico de cambios de tickets con valores viejos y nuevos en columnas separadas';

