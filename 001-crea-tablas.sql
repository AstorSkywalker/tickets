CREATE TABLE TK_TICKETS (
        id_ticket INTEGER generated by default on null as identity (start with 1 increment by 1) primary key,        
        NOMBRE_TICKET      VARCHAR2(50) NOT NULL,
        descripcion CLOB NOT NULL,
        id_usuario_reporta  integer not null,
        id_tecnico_asignado integer,
        id_categoria   integer not null,
        id_prioridad   integer not null,
        id_estado      integer not null,
        id_area        integer not null,
--        fecha_solicitud  date default sysdate not null,
--        fecha_asignacion date,
--        fecha_inicio     date,
--        fecha_resolucion date,
--        fecha_cierre     date,
        horas_estimadas   number (5,2),
        horas_reales      number (5,2),
        porcentaje_avance number(3,2) default 0,
        descripcion_solucion clob,
        constraint tk_tickets_id_usuario_reporta_fk
               foreign key (id_usuario_reporta)
               references tk_usuarios(id_usuario),        
        constraint tk_tickets_id_tecnico_asignado_fk
               foreign key (id_tecnico_asignado)
               references tk_usuarios(id_usuario),
        constraint tk_tickets_id_categoria_fk
               foreign key (id_categoria)
               references tk_categorias (id_categoria),
        constraint tk_tickets_id_estado_fk
               foreign key (id_estado)
                references tk_estados (id_estado),
        constraint tk_tickets_id_area_fk
               foreign key (id_area)
                references tk_areas (id_area),
        constraint tk_tickets_id_prioridad_fk
               foreign key (id_prioridad)
                references tk_prioridades (id_prioridad),
        constraint tk_tickets_porcentaje_avance_ck
               check (porcentaje_avance between 0 and 100)
        constraint tk_tickets_horas_estimadas_ck
               check (horas_estimadas >= 0),
        constraint tk_tickets_horas_reales_ck
               check (horas_reales >= 0),
  USUARIO_CREACION       VARCHAR2(128)     DEFAULT USER,
  FECHA_CREACION         TIMESTAMP(6)      DEFAULT SYSDATE,
  USUARIO_ACTUALIZACION  VARCHAR2(128),
  FECHA_ACTUALIZACION    TIMESTAMP(6)
);

