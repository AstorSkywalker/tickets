MERGE INTO TK_ROLES D
USING (
    SELECT 'ADMINISTRADOR' NOMBRE_ROL,
           'Administración completa del sistema' DESCRIPCION
      FROM DUAL
    UNION ALL
    SELECT 'TECNICO',
           'Atención y resolución de tickets'
      FROM DUAL
    UNION ALL
    SELECT 'USUARIO',
           'Registro y seguimiento de solicitudes'
      FROM DUAL
) S
ON (D.NOMBRE_ROL = S.NOMBRE_ROL)
WHEN NOT MATCHED THEN
    INSERT (NOMBRE_ROL, DESCRIPCION)
    VALUES (S.NOMBRE_ROL, S.DESCRIPCION);


MERGE INTO TK_CAT_PRIORIDADES D
USING (
    SELECT 'BAJA' NOMBRE_PRIORIDAD, 1 NIVEL, 72 TIEMPO_SLA_HORAS FROM DUAL
    UNION ALL
    SELECT 'MEDIA', 2, 24 FROM DUAL
    UNION ALL
    SELECT 'ALTA', 3, 8 FROM DUAL
    UNION ALL
    SELECT 'CRITICA', 4, 4 FROM DUAL
) S
ON (D.NOMBRE_PRIORIDAD = S.NOMBRE_PRIORIDAD)
WHEN NOT MATCHED THEN
    INSERT (NOMBRE_PRIORIDAD, NIVEL, TIEMPO_SLA_HORAS)
    VALUES (S.NOMBRE_PRIORIDAD, S.NIVEL, S.TIEMPO_SLA_HORAS);


MERGE INTO TK_CAT_ESTADOS D
USING (
    SELECT 'NUEVO' NOMBRE_ESTADO,
           'Ticket registrado y pendiente de revisión' DESCRIPCION_ESTADO,
           'N' CERRADO,
           1 ORDEN_VISUALIZACION
      FROM DUAL
    UNION ALL
    SELECT 'ASIGNADO',
           'Ticket asignado a un técnico',
           'N',
           2
      FROM DUAL
    UNION ALL
    SELECT 'EN_PROCESO',
           'Ticket actualmente en atención',
           'N',
           3
      FROM DUAL
    UNION ALL
    SELECT 'EN_ESPERA',
           'Ticket en espera de información o recurso',
           'N',
           4
      FROM DUAL
    UNION ALL
    SELECT 'RESUELTO',
           'Ticket resuelto, pendiente de confirmación o cierre',
           'N',
           5
      FROM DUAL
    UNION ALL
    SELECT 'CERRADO',
           'Ticket finalizado',
           'S',
           6
      FROM DUAL
    UNION ALL
    SELECT 'CANCELADO',
           'Ticket cancelado',
           'S',
           7
      FROM DUAL
) S
ON (D.NOMBRE_ESTADO = S.NOMBRE_ESTADO)
WHEN NOT MATCHED THEN
    INSERT
    (
        NOMBRE_ESTADO,
        DESCRIPCION_ESTADO,
